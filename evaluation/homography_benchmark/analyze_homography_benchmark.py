def generate_all_plots(df: pd.DataFrame, stats: Dict[str, Any], plots_dir: str, lang: str = 'en'):
    """Generates all 6 figures for a given language."""
    os.makedirs(plots_dir, exist_ok=True)
    print(f"\n[INFO] Generating 6 scientific plots in {lang.upper()} ({plots_dir})...")
    plot_figure_1_correlation(df, os.path.join(plots_dir, "fig1_distance_correlation_scatter.png"), lang=lang)
    plot_figure_2_divergence(df, os.path.join(plots_dir, "fig2_divergence_vs_distance.png"), lang=lang)
    plot_figure_3_bev_map(df, os.path.join(plots_dir, "fig3_spatial_bev_error_map.png"), lang=lang)
    plot_figure_4_classes_boxplot(df, os.path.join(plots_dir, "fig4_class_comparison_boxplots.png"), lang=lang)
    plot_figure_5_histogram_kde(df, os.path.join(plots_dir, "fig5_error_distribution_hist_kde.png"), lang=lang)
    plot_figure_6_dashboard(df, stats, os.path.join(plots_dir, "fig6_executive_summary_dashboard.png"), lang=lang)

    json_path = os.path.join(plots_dir, "homography_benchmark_stats.json")
    with open(json_path, 'w', encoding='utf-8') as f:
        json.dump(stats, f, indent=2, ensure_ascii=False)


def main():
    parser = argparse.ArgumentParser(description="Statistical Analysis & Scientific Plot Generator for Homography Benchmark")
    parser.add_argument('--csv', type=str, default=None,
                        help="Specific CSV file to analyze (default: latest in results/)")
    parser.add_argument('--results-dir', type=str, default=DEFAULT_RESULTS_DIR,
                        help="Folder containing CSV benchmark files")
    parser.add_argument('--plots-dir', type=str, default=DEFAULT_PLOTS_DIR_EN,
                        help="Output directory for plots")
    parser.add_argument('--lang', type=str, default='both', choices=['en', 'fr', 'both'],
                        help="Language for plots: 'en', 'fr', or 'both' (default: both)")

    args = parser.parse_args()

    csv_file = args.csv
    if not csv_file:
        csv_files = find_benchmark_csv_files(args.results_dir)
        if not csv_files:
            print(f"[ERROR] No CSV file found in {args.results_dir}")
            sys.exit(1)
        csv_file = csv_files[-1]

    print("\n" + "═" * 70)
    print("  HOMOGRAPHY BENCHMARK STATISTICAL ANALYSIS ($H_{old}$ VS $H_{new}$)")
    print("═" * 70)
    print(f"[INFO] Source file: {os.path.basename(csv_file)}")

    # 1. English generation
    if args.lang in ['en', 'both']:
        df_en = load_and_preprocess_data(csv_file, lang='en')
        stats_en = compute_statistics(df_en)
        generate_all_plots(df_en, stats_en, args.plots_dir, lang='en')

    # 2. French generation
    if args.lang in ['fr', 'both']:
        df_fr = load_and_preprocess_data(csv_file, lang='fr')
        stats_fr = compute_statistics(df_fr)
        fr_dir = DEFAULT_PLOTS_DIR_FR if args.lang == 'both' else args.plots_dir
        generate_all_plots(df_fr, stats_fr, fr_dir, lang='fr')

    print("\n" + "═" * 70)
    print("  SUMMARY OF STATISTICAL RESULTS")
    print("═" * 70)
    print(f"  • Total Detections          : {stats_en['total_detections']:,}")
    print(f"  • Global Median Difference  : {stats_en['divergence_old_vs_new']['median_delta_cm']:.2f} cm")
    print(f"  • 90th Percentile (P90)     : {stats_en['divergence_old_vs_new']['p90_delta_cm']:.2f} cm")
    print(f"  • Maximum Discrepancy       : {stats_en['divergence_old_vs_new']['max_delta_cm']:.1f} cm")
    print("─" * 70)
    for b_name, b_data in stats_en['brackets'].items():
        print(f"  • {b_name:<24} : Median = {b_data['median_delta_cm']:.1f} cm | P90 = {b_data['p90_delta_cm']:.1f} cm (N={b_data['count']:,})")
    print("═" * 70)
    print(f"\n[SUCCESS] All plots generated in 300 DPI:")
    print(f"  English plots -> {args.plots_dir}")
    if args.lang == 'both':
        print(f"  French plots  -> {DEFAULT_PLOTS_DIR_FR}\n")


if __name__ == '__main__':
    main()
