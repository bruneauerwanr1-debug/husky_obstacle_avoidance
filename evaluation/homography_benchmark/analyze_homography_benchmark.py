def find_benchmark_csv_files(results_dir: str) -> List[str]:
    """Finds all benchmark CSV files in the results directory."""
    pattern = os.path.join(results_dir, "yolo_homography_benchmark_*.csv")
    return sorted(glob.glob(pattern))


def load_and_preprocess_data(csv_path: str, lang: str = 'en') -> pd.DataFrame:
    """Loads CSV file and computes derived columns."""
    if not os.path.isfile(csv_path):
        raise FileNotFoundError(f"File not found: {csv_path}")

    df = pd.read_csv(csv_path)

    req_cols = ['distance_homography_old_m', 'distance_homography_new_m']
    for c in req_cols:
        if c not in df.columns:
            raise ValueError(f"Required column missing in CSV: {c}")

    if 'delta_old_vs_new_cm' not in df.columns:
        df['delta_old_vs_new_cm'] = (df['distance_homography_old_m'] - df['distance_homography_new_m']).abs() * 100.0

    df['delta_old_minus_new_m'] = df['distance_homography_old_m'] - df['distance_homography_new_m']
    df['delta_old_minus_new_cm'] = df['delta_old_minus_new_m'] * 100.0

    bins = [0.0, 1.0, 2.0, 3.5, 50.0]
    if lang == 'en':
        labels = ['< 1.0 m (Danger)', '1.0 - 2.0 m (Warning)', '2.0 - 3.5 m (Medium)', '> 3.5 m (Long Range)']
    else:
        labels = ['< 1.0 m (Danger)', '1.0 - 2.0 m (Alerte)', '2.0 - 3.5 m (Moyenne)', '> 3.5 m (Lointain)']

    df['distance_bracket'] = pd.cut(df['distance_homography_new_m'], bins=bins, labels=labels, right=False)
    return df


