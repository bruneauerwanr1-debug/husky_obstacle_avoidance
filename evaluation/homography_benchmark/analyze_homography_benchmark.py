def compute_statistics(df: pd.DataFrame) -> Dict[str, Any]:
    """Computes global and stratified statistical metrics."""
    stats = {}
    total_count = len(df)
    stats['total_detections'] = total_count

    d_old = df['distance_homography_old_m']
    d_new = df['distance_homography_new_m']
    delta_cm = df['delta_old_vs_new_cm']

    stats['h_old'] = {
        'mean_m': float(d_old.mean()),
        'median_m': float(d_old.median()),
        'std_m': float(d_old.std()),
        'min_m': float(d_old.min()),
        'max_m': float(d_old.max()),
        'p25_m': float(d_old.quantile(0.25)),
        'p75_m': float(d_old.quantile(0.75)),
    }

    stats['h_new'] = {
        'mean_m': float(d_new.mean()),
        'median_m': float(d_new.median()),
        'std_m': float(d_new.std()),
        'min_m': float(d_new.min()),
        'max_m': float(d_new.max()),
        'p25_m': float(d_new.quantile(0.25)),
        'p75_m': float(d_new.quantile(0.75)),
    }

    stats['divergence_old_vs_new'] = {
        'mean_delta_cm': float(delta_cm.mean()),
        'median_delta_cm': float(delta_cm.median()),
        'std_delta_cm': float(delta_cm.std()),
        'max_delta_cm': float(delta_cm.max()),
        'p90_delta_cm': float(delta_cm.quantile(0.90)),
        'p95_delta_cm': float(delta_cm.quantile(0.95)),
    }

    # Depth Ground Truth (if present)
    if 'distance_depth_gt_m' in df.columns:
        valid_gt = df[df['distance_depth_gt_m'].notna() & (df['distance_depth_gt_m'] > 0.1)]
        stats['gt_paired_count'] = len(valid_gt)
        if len(valid_gt) > 0:
            err_old = (valid_gt['distance_homography_old_m'] - valid_gt['distance_depth_gt_m']).abs() * 100.0
            err_new = (valid_gt['distance_homography_new_m'] - valid_gt['distance_depth_gt_m']).abs() * 100.0

            stats['depth_gt_comparison'] = {
                'mae_old_cm': float(err_old.mean()),
                'median_err_old_cm': float(err_old.median()),
                'rmse_old_cm': float(np.sqrt((err_old**2).mean())),
                'mae_new_cm': float(err_new.mean()),
                'median_err_new_cm': float(err_new.median()),
                'rmse_new_cm': float(np.sqrt((err_new**2).mean())),
            }

    # Distance brackets
    stats['brackets'] = {}
    for bracket_name, grp in df.groupby('distance_bracket', observed=False):
        if len(grp) > 0:
            stats['brackets'][str(bracket_name)] = {
                'count': len(grp),
                'percent': float(len(grp) / total_count * 100.0),
                'mean_old_m': float(grp['distance_homography_old_m'].mean()),
                'mean_new_m': float(grp['distance_homography_new_m'].mean()),
                'median_delta_cm': float(grp['delta_old_vs_new_cm'].median()),
                'p90_delta_cm': float(grp['delta_old_vs_new_cm'].quantile(0.90)),
                'max_delta_cm': float(grp['delta_old_vs_new_cm'].max()),
            }

    # Obstacle classes
    stats['classes'] = {}
    if 'obstacle_class' in df.columns:
        for cls_name, grp in df.groupby('obstacle_class'):
            if len(grp) >= 5:
                stats['classes'][str(cls_name)] = {
                    'count': len(grp),
                    'mean_new_m': float(grp['distance_homography_new_m'].mean()),
                    'median_new_m': float(grp['distance_homography_new_m'].median()),
                    'median_delta_cm': float(grp['delta_old_vs_new_cm'].median()),
                    'p90_delta_cm': float(grp['delta_old_vs_new_cm'].quantile(0.90)),
                }

    return stats


