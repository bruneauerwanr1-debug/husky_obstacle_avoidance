def plot_figure_5_histogram_kde(df: pd.DataFrame, out_path: str, lang: str = 'en'):
    """Fig 5: Histogram and KDE probability density of discrepancies."""
    fig, ax = plt.subplots(figsize=(8.5, 5.5))

    deltas = df['delta_old_vs_new_cm'].dropna()
    deltas_clipped = deltas[deltas <= 50.0]

    lbl_hist = 'Difference Histogram' if lang == 'en' else 'Histogramme des écarts'
    lbl_kde = 'KDE Probability Density' if lang == 'en' else 'Densité KDE'
    lbl_x = 'Absolute Difference $\\Delta |H_{old} - H_{new}|$ [cm]' if lang == 'en' else 'Écart Absolu $\\Delta |H_{old} - H_{new}|$ [cm]'
    lbl_y = 'Probability Density' if lang == 'en' else 'Densité de Probabilité'
    title = 'Statistical Distribution of Homography Differences' if lang == 'en' else 'Distribution Statistique des Écarts entre Homographies'

    ax.hist(deltas_clipped, bins=40, density=True,
            color=C_NEW, alpha=0.55, edgecolor='#1B4332', label=lbl_hist)

    try:
        from scipy.stats import gaussian_kde
        kde = gaussian_kde(deltas_clipped)
        x_grid = np.linspace(0, 50, 200)
        ax.plot(x_grid, kde(x_grid), color='#081C15', linewidth=2.5, label=lbl_kde)
    except Exception:
        pass

    med = deltas.median()
    mean = deltas.mean()
    p90 = deltas.quantile(0.90)

    lbl_med_val = f'Median = {med:.1f} cm' if lang == 'en' else f'Médiane = {med:.1f} cm'
    lbl_mean_val = f'Mean = {mean:.1f} cm' if lang == 'en' else f'Moyenne = {mean:.1f} cm'
    lbl_p90_val = f'90th Percentile = {p90:.1f} cm' if lang == 'en' else f'90ème percentile = {p90:.1f} cm'

    ax.axvline(med, color=C_OLD, linestyle='-', linewidth=2.0, label=lbl_med_val)
    ax.axvline(mean, color='#1D3557', linestyle='--', linewidth=2.0, label=lbl_mean_val)
    ax.axvline(p90, color='#F4A261', linestyle=':', linewidth=2.0, label=lbl_p90_val)

    ax.set_xlim(0, 45)
    ax.set_xlabel(lbl_x, fontweight='bold')
    ax.set_ylabel(lbl_y, fontweight='bold')
    ax.set_title(title, pad=12, fontweight='bold')
    ax.legend(loc='upper right', framealpha=0.95)

    plt.tight_layout()
    plt.savefig(out_path)
    plt.close()
    print(f"  ✓ [{lang.upper()}] Figure 5: {os.path.basename(out_path)}")


