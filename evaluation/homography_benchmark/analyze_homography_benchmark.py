    lbl_scat = 'Individual Discrepancies' if lang == 'en' else 'Écarts individuels'
    lbl_med = 'Median Difference $\\Delta |H_{old} - H_{new}|$' if lang == 'en' else 'Écart Médian $\\Delta |H_{old} - H_{new}|$'
    lbl_p = 'Inter-Percentile Range [P10 - P90]' if lang == 'en' else 'Intervalle Inter-Percentiles [P10 - P90]'
    lbl_tol = 'Safety Tolerance (5 cm)' if lang == 'en' else 'Tolérance de sécurité (5 cm)'
    lbl_lim = '$H_{old}$ Calibration Limit (1.5 m)' if lang == 'en' else 'Limite calibration $H_{old}$ (1.5 m)'
    lbl_x = 'Obstacle Distance from Robot [m]' if lang == 'en' else 'Distance de l\'Obstacle au Robot [m]'
    lbl_y = 'Absolute Difference $\\Delta D = |D_{old} - D_{new}|$ [cm]' if lang == 'en' else 'Écart Absolu $\\Delta D = |D_{old} - D_{new}|$ [cm]'
    title = 'Metric Divergence between $H_{old}$ and $H_{new}$ vs Distance' if lang == 'en' else 'Divergence Métrique entre $H_{old}$ et $H_{new}$ selon la Distance'

